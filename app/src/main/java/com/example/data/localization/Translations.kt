    fun get(lang: AppLanguage, key: String): String {
        val map = when (lang) {
            AppLanguage.EN -> EN
            AppLanguage.TA -> TA
            AppLanguage.HI -> HI
            AppLanguage.TE -> TE
            AppLanguage.KN -> KN
            AppLanguage.ML -> ML
            AppLanguage.BN -> BN
            AppLanguage.MR -> MR
        }
        return map[key] ?: EN[key] ?: key
    }

    fun smartTranslate(text: String, lang: AppLanguage): String {
        if (text.isBlank()) return text
        if (lang == AppLanguage.EN) return text

        val uiDict = uiTermsMap[lang]
        if (uiDict != null) {
            val uiTrans = uiDict[text]
            if (uiTrans != null) return uiTrans
        }

        val map = when (lang) {
            AppLanguage.EN -> EN
            AppLanguage.TA -> TA
            AppLanguage.HI -> HI
            AppLanguage.TE -> TE
            AppLanguage.KN -> KN
            AppLanguage.ML -> ML
            AppLanguage.BN -> BN
            AppLanguage.MR -> MR
        }
        val direct = map[text] ?: EN[text]
        if (direct != null && direct != text) return direct

        val sentences = sentenceMap[lang] ?: return text
        for ((engKey, translated) in sentences) {
            if (text.contains(engKey, ignoreCase = true) || engKey.contains(text, ignoreCase = true)) {
                return translated
            }
        }
        return text
    }
